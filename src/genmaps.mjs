// emit a frozen suite of generated level defs → src/genlevels.js
//   node src/genmaps.mjs --n=50 --start=101
// convention: a generated level's ID IS its seed — levelDefForSeed(id) fully
// reproduces the def, so the suite is inspectable and re-derivable.
import { writeFileSync } from 'node:fs';
import { levelDefForSeed, mapParams, MAP_PARAM_DIM } from './mapgen.js';
import { CONFIG } from './config.js';

const arg = (k, d) => { const m = process.argv.find((a) => a.startsWith(`--${k}=`)); return m ? +m.split('=')[1] : d; };
const N = arg('n', 50), START = arg('start', 101);
const out = {}, rows = [];
for (let i = 0; i < N; i++) {
  const id = START + i;
  const def = levelDefForSeed(id);
  out[id] = def;
  CONFIG.levels[id] = def; // so mapParams can resolve it for the table
  const p = mapParams(id);
  rows.push({ id, cols: Math.round(p[0] * 80), water: p[2] ? 'blob' : p[3] ? 'river' : '-',
    wfrac: +p[1].toFixed(3), bias: p[4] ? 'L' : p[5] ? 'R' : '-', bridges: !!p[6],
    spawn: +(p[7] * 14).toFixed(1), hunger: Math.round(p[8] * 140), demand: +p[9].toFixed(2),
    stars: (def.win?.stars ?? [5, 8, 11]).join('/') });
}
const src = '// generated by src/genmaps.mjs — do not hand-edit; regenerate with\n' +
  `//   node src/genmaps.mjs --n=${N} --start=${START}\n` +
  `export const GEN_LEVELS = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(new URL('./genlevels.js', import.meta.url), src);
console.table(rows);
console.log(`wrote ${N} defs → src/genlevels.js (param dim ${MAP_PARAM_DIM})`);
